import type {
  VideoCategorySection,
  VideoChannelSection,
  VideoInfo,
} from "~/types/video";

/** content_type of a video in the shared tables (<language>_vocabulary…). */
export const VIDEOS_CONTENT_TYPE = 3;

interface VideoCategoryDisplay {
  /** Display label; the ids are PascalCase keys, not readable text */
  label: string;
  /** Font Awesome classes */
  icon: string;
  /** Position of the category in lists (1 = first) */
  orderId: number;
}

/**
 * Video categories (the category column of fr_videos), in the order of the Figma page.
 * Single source of truth: VideoCategory and VIDEO_CATEGORY_IDS are derived
 * from these keys, so adding a category here is all it takes.
 * Icons are Font Awesome Solid, like the Figma VideoFilterChip.
 */
export const VIDEO_CATEGORIES = {
  SlowFrench: {
    label: "Slow French",
    icon: "fa-solid fa-person-walking",
    orderId: 1,
  },
  MovieClips: { label: "Movie Clips", icon: "fa-solid fa-film", orderId: 2 },
  MovieScenes: { label: "Movie Scenes", icon: "fa-solid fa-clapperboard", orderId: 3 },
  Vlogs: { label: "Vlogs", icon: "fa-solid fa-video", orderId: 4 },
  History: {
    label: "History",
    icon: "fa-solid fa-building-columns",
    orderId: 5,
  },
  Interviews: {
    label: "Interviews",
    icon: "fa-solid fa-microphone",
    orderId: 6,
  },
  Music: { label: "Music", icon: "fa-solid fa-music", orderId: 7 },
} as const satisfies Record<string, VideoCategoryDisplay>;

export type VideoCategory = keyof typeof VIDEO_CATEGORIES;

/** Category ids, sorted by orderId. */
// Object.keys is typed string[]; the cast is safe as VIDEO_CATEGORIES is a
// literal whose keys are exactly the VideoCategory ids.
export const VIDEO_CATEGORY_IDS = (
  Object.keys(VIDEO_CATEGORIES) as VideoCategory[]
).sort(
  (a, b) => VIDEO_CATEGORIES[a].orderId - VIDEO_CATEGORIES[b].orderId,
) as readonly VideoCategory[];

/** Speech rates of a video, with the label shown on its meta chip. */
export const SPEECH_RATE_LABELS = {
  slow: "Slow",
  normal: "Normal",
  fast: "Fast",
} as const;

export type SpeechRate = keyof typeof SPEECH_RATE_LABELS;

/** Subtitle kinds of a video, with the label shown on its meta chip. */
export const SUBTITLES_LABELS = {
  native: "FR subtitles",
  auto: "Auto subtitles",
} as const;

export type SubtitlesKind = keyof typeof SUBTITLES_LABELS;

// Lowercased id → id, so database values match whatever their casing.
const CATEGORY_BY_KEY = new Map<string, VideoCategory>(
  VIDEO_CATEGORY_IDS.map((category) => [category.toLowerCase(), category]),
);

// Spaces, underscores and hyphens, ignored when matching database values.
const SEPARATORS = /[\s_-]+/g;

/** Lowercases a database value and drops its separators: "Slow_French" → "slowfrench". */
function normalize(value: string | null): string {
  return value?.replace(SEPARATORS, "").toLowerCase() ?? "";
}

/**
 * Resolves a category value from the database, ignoring case and separators
 * ("Slow French", "slow_french", "SlowFrench" → "SlowFrench").
 * @returns The VideoCategory, or null when the value is empty or unknown
 */
export function toVideoCategory(value: string | null): VideoCategory | null {
  return CATEGORY_BY_KEY.get(normalize(value)) ?? null;
}

/**
 * Resolves a speech_rate value from the database, case-insensitively.
 * @returns The SpeechRate, or null when the value is empty or unknown
 */
export function toSpeechRate(value: string | null): SpeechRate | null {
  const key = normalize(value);
  return key in SPEECH_RATE_LABELS ? (key as SpeechRate) : null;
}

// caption_type values meaning automatic (YouTube ASR) captions; any other
// value of a captioned video counts as human-made French subtitles.
const AUTO_CAPTION_TYPES = new Set([
  "auto",
  "asr",
  "automatic",
  "generated",
  "autogenerated",
]);

/**
 * Resolves the subtitles of a video from has_captions and caption_type.
 * @returns "auto" for automatic captions, "native" for the others, null without captions
 */
export function toSubtitlesKind(
  hasCaptions: boolean,
  captionType: string | null,
): SubtitlesKind | null {
  if (!hasCaptions) return null;
  return AUTO_CAPTION_TYPES.has(normalize(captionType)) ? "auto" : "native";
}

/**
 * Groups videos by category, in the orderId order of the categories and
 * keeping the order of the videos inside each group. Videos without a known
 * category and empty categories are left out.
 */
export function groupVideosByCategory(
  videos: readonly VideoInfo[],
): VideoCategorySection[] {
  return VIDEO_CATEGORY_IDS.map((category) => ({
    category,
    videos: videos.filter((video) => video.category === category),
  })).filter((section) => section.videos.length > 0);
}

/**
 * Groups videos by YouTube channel: channels with the most videos first, then
 * by name; videos with an unknown channel come last. Keeps the video order
 * inside each group.
 */
export function groupVideosByChannel(
  videos: readonly VideoInfo[],
): VideoChannelSection[] {
  const byChannel = new Map<string | null, VideoChannelSection>();
  for (const video of videos) {
    const section = byChannel.get(video.channel) ?? {
      channel: video.channel,
      avatarUrl: null,
      videos: [],
    };
    section.videos.push(video);
    section.avatarUrl ??= video.channelAvatarUrl;
    byChannel.set(video.channel, section);
  }
  return [...byChannel.values()].sort(compareChannelSections);
}

function compareChannelSections(
  a: VideoChannelSection,
  b: VideoChannelSection,
): number {
  if (a.channel === null) return 1;
  if (b.channel === null) return -1;
  return (
    b.videos.length - a.videos.length || a.channel.localeCompare(b.channel)
  );
}

/** Most recently published video; the first one when none is dated. */
function latestVideo(videos: readonly VideoInfo[]): VideoInfo | null {
  return videos.reduce<VideoInfo | null>((latest, video) => {
    if (!latest) return video;
    if (!video.publishedAt) return latest;
    if (!latest.publishedAt || video.publishedAt > latest.publishedAt)
      return video;
    return latest;
  }, null);
}

/**
 * Picks the video highlighted in "Featured this week": the latest of the
 * videos marked is_featured, else the latest video.
 * @returns The video, or null when the list is empty
 */
export function pickFeaturedVideo(
  videos: readonly VideoInfo[],
): VideoInfo | null {
  return (
    latestVideo(videos.filter((video) => video.isFeatured)) ??
    latestVideo(videos)
  );
}

const SECONDS_PER_MINUTE = 60;
const SECONDS_PER_HOUR = 3600;
const PAD_LENGTH = 2;

/**
 * Formats a video length like YouTube does: "8:42", "14:20", "1:02:05".
 * @param seconds - Length in seconds; decimals are dropped
 * @returns The formatted length, or null when the input is null, negative or not a number
 */
export function formatVideoDuration(
  seconds: number | null | undefined,
): string | null {
  if (seconds == null || !Number.isFinite(seconds) || seconds < 0) return null;
  const total = Math.floor(seconds);
  const hours = Math.floor(total / SECONDS_PER_HOUR);
  const minutes = Math.floor((total % SECONDS_PER_HOUR) / SECONDS_PER_MINUTE);
  const secs = String(total % SECONDS_PER_MINUTE).padStart(PAD_LENGTH, "0");
  if (hours === 0) return `${minutes}:${secs}`;
  return `${hours}:${String(minutes).padStart(PAD_LENGTH, "0")}:${secs}`;
}

/**
 * Formats a video length in whole minutes, for meta chips: 860 → "14 min".
 * Videos shorter than a minute show "1 min".
 * @returns The label, or null when the input is null, negative or not a number
 */
export function formatVideoMinutes(
  seconds: number | null | undefined,
): string | null {
  if (seconds == null || !Number.isFinite(seconds) || seconds < 0) return null;
  return `${Math.max(1, Math.round(seconds / SECONDS_PER_MINUTE))} min`;
}

/** One fact shown as a VideoMetaChip. */
export interface VideoMetaItem {
  /** Stable key for v-for */
  id: "duration" | "subtitles" | "speechRate";
  /** Font Awesome classes */
  icon: string;
  label: string;
}

/**
 * Lists the meta chips of a video, in display order (length, subtitles,
 * speech rate), skipping the unknown ones.
 * @param duration - Length in seconds; pass null to leave the length out
 */
export function buildVideoMetaItems(
  subtitles: SubtitlesKind | null,
  speechRate: SpeechRate | null,
  duration: number | null = null,
): VideoMetaItem[] {
  const items: VideoMetaItem[] = [];
  const minutes = formatVideoMinutes(duration);
  if (minutes)
    items.push({ id: "duration", icon: "fa-regular fa-clock", label: minutes });
  if (subtitles)
    items.push({
      id: "subtitles",
      icon: "fa-regular fa-closed-captioning",
      label: SUBTITLES_LABELS[subtitles],
    });
  if (speechRate)
    items.push({
      id: "speechRate",
      icon: "fa-solid fa-person-walking",
      label: SPEECH_RATE_LABELS[speechRate],
    });
  return items;
}

/**
 * What the Videos page shows. Without a category: the featured video, then one
 * section per category. With a category: one section per YouTube channel.
 */
export interface VideoPageContent {
  featured: VideoInfo | null;
  sections: VideoCategorySection[];
  channels: VideoChannelSection[];
}

/**
 * Lays out the Videos page. With no category, picks the featured video and
 * groups the others by category (the featured video is not repeated in its
 * section). With a category, groups its videos by channel, with no featured one.
 * @param category - Only keep this category; every category when null
 */
export function buildVideoPageContent(
  videos: readonly VideoInfo[],
  category: VideoCategory | null,
): VideoPageContent {
  if (category) {
    const inCategory = videos.filter((video) => video.category === category);
    return {
      featured: null,
      sections: [],
      channels: groupVideosByChannel(inCategory),
    };
  }
  const featured = pickFeaturedVideo(videos);
  const others = videos.filter((video) => video !== featured);
  return { featured, sections: groupVideosByCategory(others), channels: [] };
}

/** A video stays NEW this many days after its publication. */
export const NEW_VIDEO_DAYS = 14;
const MS_PER_DAY = 24 * 60 * 60 * 1000;

/**
 * Whether a video was published in the last NEW_VIDEO_DAYS days.
 * @param publishedAt - ISO date of publication; never new when null or invalid
 * @param now - Reference date, injectable for tests
 */
export function isNewVideo(
  publishedAt: string | null,
  now: Date = new Date(),
): boolean {
  if (!publishedAt) return false;
  const published = Date.parse(publishedAt);
  if (Number.isNaN(published)) return false;
  const age = now.getTime() - published;
  return age >= 0 && age <= NEW_VIDEO_DAYS * MS_PER_DAY;
}
